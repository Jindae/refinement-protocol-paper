orange <- "#D55E00"
green <- "#009E73"
gray <- "#737373"
light_gray <- "#D9D9D9"
grid_gray <- "#E6E6E6"

open_pdf <- function(name, width, height) {
  cairo_pdf(
    filename = file.path(output_dir, name),
    width = width,
    height = height,
    family = "Verdana"
  )
}

