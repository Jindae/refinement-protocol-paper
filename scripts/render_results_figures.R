format_signed_pp <- function(value) {
  value <- 100 * value
  if (value < 0) sprintf("$-$%.2f", abs(value)) else sprintf("+%.2f", value)
}

significance_marker <- function(low, high) {
  if (low > 0 || high < 0) "\\textsuperscript{$\\dagger$}" else ""
}

